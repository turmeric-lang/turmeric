const char *turi_caps_describe(TuriCaps caps, char *buf, size_t n) {
    static const struct { TuriCaps bit; const char *name; } k_names[] = {
        { TURI_CAP_IO,       "io"       },
        { TURI_CAP_FFI,      "ffi"      },
        { TURI_CAP_INLINE_C, "inline-c" },
        { TURI_CAP_ASYNC,    "async"    },
        { TURI_CAP_UNSAFE,   "unsafe"   },
        { TURI_CAP_IMPORT,   "import"   },
        { TURI_CAP_FS,       "fs"       },
        { TURI_CAP_PROC,     "proc"     },
        { TURI_CAP_ENV,      "env"      },
    };
    if (!buf || n == 0) return "";
    buf[0] = '\0';
    size_t used = 0;
    for (size_t i = 0; i < sizeof k_names / sizeof k_names[0]; i++) {
        if (!(caps & k_names[i].bit)) continue;
        size_t len = strlen(k_names[i].name);
        size_t sep = used ? 1 : 0;
        if (used + sep + len + 1 > n) break;
        if (sep) buf[used++] = ',';
        memcpy(buf + used, k_names[i].name, len + 1);
        used += len;
    }
    return buf;
}
