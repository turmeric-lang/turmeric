/* native_caps.c -- the capability each builtin interpreter native requires.
 *
 * security-audit-plan WP3 (S-1).  Every native that turi_env_new registers --
 * interpreter_natives.c, collections_native.c, string_native.c, fiber.c, the
 * eval.c builtins, macro_env.c, ffi_thunk.c and main.c -- has exactly one row
 * here.  turi_env_register_native looks the name up and stamps the row's bits
 * on the closure; eval_apply_driven refuses the call when the calling env does
 * not hold every one of them.  One check at the dispatch, not one per native.
 *
 * A row of 0 is "pure": the native reaches nothing outside the interpreter's
 * own heap.  Classification is by what the CALLER can make the native do, so a
 * native that writes stderr only on its own panic path is still 0.  What a 0
 * row does NOT promise is memory safety: most natives take handles as bare
 * integers, and refusing a forged one is the handle-signature column's job
 * (S-5 in the security audit plan; k_handle_rows[] below).
 *
 * Rules for a new native:
 *   - add its row here, in strcmp order (the table is binary-searched);
 *   - tests/turi/sandbox-eval.c fails for any native a fresh env holds that has
 *     no row, and for any non-zero row a sandboxed env can call;
 *   - the reason goes in the trailing comment of every non-zero row.
 *
 * Natives an embedder registers under a name that is not in this table carry
 * no requirement: the embedder chose to expose them.  Use
 * turi_env_register_native_caps to give one a requirement explicitly.
 *
 * The prose version, with the rationale for each class, is the "Capability
 * classification" table in docs/guides/sandboxing-guide.md. */
