static const char *const BASH_SCRIPT[] = {
    "# bash completion for tur -- generated by `tur completion bash`.\n",
    "#\n",
    "# Install:\n",
    "#   tur completion bash > /usr/local/etc/bash_completion.d/tur\n",
    "# or source it directly from ~/.bashrc:\n",
    "#   source <(tur completion bash)\n",
    "\n",
    "__tur_commands=\"build run just check test repl fmt format emit-c emit-h compile link\n",
    "interpret debug eval doc explain parse-check audit-spans lsp lsp-lite dap mcp\n",
    "worker init new add add-cmake fetch emit-cmake install uninstall list upgrade\n",
    "experiments dialects image-info image-verify completion demangle\"\n",
    "\n",
    "__tur_global_flags=\"--help --version --no-color --json --json-diagnostics\n",
    "--strict-effects -Werror=strict-effects --strict-refine --no-contracts --keep-contracts\n",
    "--warn-unused-result --panic-abort --no-auto-spice --enable=\"\n",
    "\n",
    "# Recipe names from the enclosing Justfile (empty when there is none).\n",
    "__tur_recipes() {\n",
    "    \"${COMP_WORDS[0]}\" run --list 2>/dev/null | awk 'NF { print $1 }'\n",
    "}\n",
    "\n",
    "__tur_turfiles() {\n",
    "    compgen -f -X '!*.tur' -- \"$1\"\n",
    "    compgen -f -X '!*.tur.sweet' -- \"$1\"\n",
    "    compgen -d -- \"$1\"\n",
    "}\n",
    "\n",
    "_tur() {\n",
    "    local cur prev cmd\n",
    "    cur=\"${COMP_WORDS[COMP_CWORD]}\"\n",
    "    prev=\"${COMP_WORDS[COMP_CWORD-1]}\"\n",
    "\n",
    "    # First non-flag word after the binary is the subcommand.\n",
    "    local i\n",
    "    cmd=\"\"\n",
    "    for (( i=1; i < COMP_CWORD; i++ )); do\n",
    "        case \"${COMP_WORDS[i]}\" in\n",
    "            -*) ;;\n",
    "            *) cmd=\"${COMP_WORDS[i]}\"; break ;;\n",
    "        esac\n",
    "    done\n",
    "\n",
    "    if [ -z \"$cmd\" ]; then\n",
    "        COMPREPLY=( $(compgen -W \"$__tur_commands $__tur_global_flags\" -- \"$cur\") )\n",
    "        return 0\n",
    "    fi\n",
    "\n",
    "    # Flag values that take a path.\n",
    "    case \"$prev\" in\n",
    "        -o|--build-dir|-B|--justfile|--output-dir)\n",
    "            COMPREPLY=( $(compgen -f -- \"$cur\") ); return 0 ;;\n",
    "        --chdir|-I)\n",
    "            COMPREPLY=( $(compgen -d -- \"$cur\") ); return 0 ;;\n",
    "    esac\n",
    "\n",
    "    case \"$cmd\" in\n",
    "        run|just)\n",
    "            local flags=\"--list --all --json --dry-run --verbose --justfile\n",
    "--chdir --init --force --release\"\n",
    "            if [[ \"$cur\" == -* ]]; then\n",
    "                COMPREPLY=( $(compgen -W \"$flags\" -- \"$cur\") )\n",
    "            else\n",
    "                COMPREPLY=( $(compgen -W \"$(__tur_recipes)\" -- \"$cur\")\n",
    "                            $(__tur_turfiles \"$cur\") )\n",
    "            fi\n",
    "            ;;\n",
    "        build)\n",
    "            if [[ \"$cur\" == -* ]]; then\n",
    "                COMPREPLY=( $(compgen -W \"-o --build-dir --release --shared --watch -I\" -- \"$cur\") )\n",
    "            else\n",
    "                COMPREPLY=( $(__tur_turfiles \"$cur\") )\n",
    "            fi\n",
    "            ;;\n",
    "        check|emit-c|emit-h|compile|interpret|debug|parse-check|audit-spans|format|repl)\n",
    "            COMPREPLY=( $(__tur_turfiles \"$cur\") )\n",
    "            ;;\n",
    "        fmt)\n",
    "            if [[ \"$cur\" == -* ]]; then\n",
    "                COMPREPLY=( $(compgen -W \"--check --diff --dry-run\" -- \"$cur\") )\n",
    "            else\n",
    "                COMPREPLY=( $(compgen -f -- \"$cur\") )\n",
    "            fi\n",
    "            ;;\n",
    "        test|init|new)\n",
    "            COMPREPLY=( $(compgen -d -- \"$cur\") )\n",
    "            ;;\n",
    "        add|add-cmake)\n",
    "            COMPREPLY=( $(compgen -W \"--path --ref --workspace\" -- \"$cur\")\n",
    "                        $(compgen -d -- \"$cur\") )\n",
    "            ;;\n",
    "        fetch)\n",
    "            COMPREPLY=( $(compgen -W \"--update --dry-run --refetch\" -- \"$cur\") )\n",
    "            ;;\n",
    "        install|uninstall|upgrade)\n",
    "            COMPREPLY=( $(compgen -W \"--path --all\" -- \"$cur\")\n",
    "                        $(compgen -d -- \"$cur\") )\n",
    "            ;;\n",
    "        list)\n",
    "            COMPREPLY=( $(compgen -W \"--verbose --outdated\" -- \"$cur\") )\n",
    "            ;;\n",
    "        completion)\n",
    "            COMPREPLY=( $(compgen -W \"zsh bash\" -- \"$cur\") )\n",
    "            ;;\n",
    "        *)\n",
    "            COMPREPLY=( $(compgen -f -- \"$cur\") )\n",
    "            ;;\n",
    "    esac\n",
    "    return 0\n",
    "}\n",
    "\n",
    "complete -F _tur tur\n",
    NULL,
};

static void emit(const char *const *lines) {
    for (int i = 0; lines[i]; i++) fputs(lines[i], stdout);
}

int usage_completion(void) {
    fprintf(stderr,
        "usage:\n"
        "  tur completion zsh              print the zsh completion script\n"
        "  tur completion bash             print the bash completion script\n"
        "\n"
        "zsh -- install into your fpath:\n"
        "  tur completion zsh > \"${fpath[1]}/_tur\" && compinit\n"
        "zsh -- or source it from ~/.zshrc:\n"
        "  source <(tur completion zsh)\n"
        "\n"
        "bash -- install:\n"
        "  tur completion bash > /usr/local/etc/bash_completion.d/tur\n"
        "bash -- or source it from ~/.bashrc:\n"
        "  source <(tur completion bash)\n"
        "\n"
        "Recipe completion for `tur run` reads `tur run --list` in the\n"
        "directory being completed, so it tracks the enclosing Justfile.\n");
    return 0;
}

int cmd_completion(int argc, char **argv) {
    if (argc < 3) {
        fprintf(stderr, "tur completion: missing shell name\n");
        usage_completion();
        return 2;
    }
    const char *shell = argv[2];
    if (strcmp(shell, "--help") == 0 || strcmp(shell, "-h") == 0)
        return usage_completion();
    if (strcmp(shell, "zsh") == 0)  { emit(ZSH_SCRIPT);  return 0; }
    if (strcmp(shell, "bash") == 0) { emit(BASH_SCRIPT); return 0; }
    fprintf(stderr,
            "tur completion: unsupported shell '%s' (expected zsh or bash)\n",
            shell);
    usage_completion();
    return 2;
}
