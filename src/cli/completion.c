/*
 * completion.c -- `tur completion <zsh|bash>`: print a shell completion script.
 *
 * The scripts are embedded rather than shipped as data files so that a bare
 * `tur` binary is enough to bootstrap completion anywhere ("source <(tur
 * completion zsh)"), with no install-prefix lookup to get wrong.
 *
 * They are stored one line per array element, not as a single concatenated
 * literal: ISO C99 only requires 4095 characters of string literal, and both
 * scripts are comfortably past that (-Woverlength-strings catches it).
 *
 * Both scripts complete `tur run` recipe names by shelling out to
 * `tur run --list` and taking the first field of each line.  That listing is
 * deliberately tolerant -- it reports aliases, hides [private] recipes, and
 * survives Justfile features the parser does not support -- so completion
 * degrades to the recipes we do understand instead of coming back empty.
 * See src/compiler/justrun.c.
 */

#include "completion.h"

#include <stdio.h>
#include <string.h>

