#!/usr/bin/env python3
"""check-let-alignment.py -- multi-line `let` binding vectors in the docs'
Turmeric snippets keep their names and their values in two straight columns.

CLAUDE.md ("Binding vectors -- align bindings under each other") asks for

    (let [x   1
          y   2
          foo (+ x y)]
      foo)

one binding per line, names in one column, values in one column.  A snippet
that is one space off still compiles, so nothing else catches it, and it is
exactly the kind of thing a reader copies: advanced-type-system-rationale's
session-types example shipped with `ch2`'s value one column right of
`[n ch1]`'s.  This check reads every ```turmeric / ```sweet-exp fence in the
docs (and whole .tur / .tur.sweet files when given) and fails for a vector
whose bindings do not line up.  Part of tests/check-docs-lint.sh.

What is checked, for `let`, `let*`, `letrec` and `loop` vectors that span
more than one line and bind more than one name:
  - every binding starts on its own line (a name on one line and its value
    on the next is "split");
  - every binding's first token (`^mut x` counts from the `^`) starts in the
    same column as the first binding's;
  - every binding's value starts in the same column.
A value that itself spans lines is fine; its continuation lines are not
bindings, and comments and blank lines between bindings are ignored.  A
`...` placeholder is skipped, and so is a vector the grammar cannot read (a
sketch in a plan, an unfinished repro): this is an alignment check, not a
parser.

Trailing comments are checked too.  Consecutive lines that each end in a `;`
comment after code form a run, and a run's comments start in one column:

    (println (color-to-int (Red)))                 ; 1
    (println (eval-expr (Add (Lit 10) (Lit 20))))  ; 30

That column is the one most of the run's lines already use (the leftmost on a
tie).  A line whose code reaches that column is exempt and keeps its comment
after its code, so one long line does not push the rest of the run right.  A
comment-only line right of the code above it continues its comment; any
other line (blank, code with no comment, a full-line comment elsewhere) ends
the run.  Strings (multi-line ones too), `#\\;`, a `#;` datum comment,
`#| ... |#` and inline C are not comments.

Usage: check-let-alignment.py [--fix] [--selftest] [path ...]
                                                   (default: docs/, README.md)
A .md path is scanned for fenced snippets; a .tur / .tur.sweet path is scanned
whole.  `--fix` rewrites the misaligned vectors in place (whitespace only:
names are moved under the first binding's, values padded to one column, a
multi-line value's continuation lines moved with it; a comment moved to its
run's column by changing only the blanks before its `;`) and reports what it
could not fix.  `--selftest` first runs the checker and the rewriter over the
samples at the bottom of this file (the rewriter once mangled a vector whose
two bindings shared a line).  Exit 1 when anything is, or is left,
misaligned.
"""
import sys
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_PATHS = ["docs", "README.md"]
# docs/api/ is generated by tools/gendocs.py; its snippets come from stdlib.
SKIP_DIRS = {"api"}
SNIPPET_LANGS = {"turmeric", "sweet-exp", "tur"}
FORMS = ("let", "let*", "letrec", "loop")
BORROW_PREFIXES = ("&", "&mut")
MAX_FIX_PASSES = 8

OPEN = {"(": ")", "[": "]", "{": "}"}
CLOSE = {v: k for k, v in OPEN.items()}


class Problem(Exception):
    pass


# -- reading ---------------------------------------------------------------

def fenced_snippets(text):
    """Yield (start_line_idx, end_line_idx, lines) for each Turmeric fence in a
    Markdown text; the indices are into text.split("\\n") and cover the body.
    A fence inside a list item is de-indented by the fence line's indent.
    As in CommonMark, a closing fence is indented at most three columns past
    the opening one's: the indented ``` that closes an inline-C block inside
    a sweet-exp `defn` is part of the snippet, not its end."""
    lines = text.split("\n")
    i = 0
    while i < len(lines):
        m = re.match(r"^(\s*)(`{3,}|~{3,})\s*([\w+-]*)", lines[i])
        if not m:
            i += 1
            continue
        indent, fence, lang = m.group(1), m.group(2), m.group(3)
        start = i + 1
        i += 1
        while i < len(lines):
            s = lines[i].strip()
            lead = len(lines[i]) - len(lines[i].lstrip(" "))
            if s.startswith(fence[0] * len(fence)) and s.strip(fence[0]) == "" \
                    and lead <= len(indent) + 3:
                break
            i += 1
        if lang in SNIPPET_LANGS:
            yield start, i, [l[len(indent):] if l.startswith(indent) else l.lstrip()
                             for l in lines[start:i]], indent
        i += 1


def inline_c_mask(lines):
    """True for each line inside a ```c ... ``` inline-C block of a snippet:
    its braces and semicolons are C, not Turmeric, and the fence line too."""
    mask, in_c = [], False
    for l in lines:
        s = l.strip().replace("\u200b", "")
        if not in_c and s.startswith("```"):
            in_c = True
            mask.append(True)
            continue
        if in_c:
            if "```" in s:
                in_c = False
            mask.append(True)
            continue
        mask.append(False)
    return mask


def tokenize(lines, mask):
    """Yield (tok, line_idx, col, end_col).  Delimiters are single tokens; a
    symbol / number / keyword / string is one token.  `;` comments are skipped;
    a string ends at its line if unterminated."""
    for li, line in enumerate(lines):
        if mask[li]:
            continue
        ci, n = 0, len(line)
        while ci < n:
            c = line[ci]
            if c in " \t":
                ci += 1
            elif c == ";":
                break
            elif line.startswith("#;", ci):
                yield "#;", li, ci, ci + 2   # datum comment: not a line comment
                ci += 2
            elif line.startswith("#\\", ci) and ci + 2 < n:
                j = ci + 3                # `#\;`, `#\(`, `#\space`
                while j < n and line[j] not in " \t;\"()[]{}":
                    j += 1
                yield line[ci:j], li, ci, j
                ci = j
            elif c in OPEN or c in CLOSE:
                yield c, li, ci, ci + 1
                ci += 1
            elif c == '"':
                j = ci + 1
                while j < n and line[j] != '"':
                    j += 2 if line[j] == "\\" else 1
                yield line[ci:j + 1], li, ci, j + 1
                ci = j + 1
            else:
                j = ci
                while j < n and line[j] not in " \t;\"()[]{}":
                    j += 1
                yield line[ci:j], li, ci, j
                ci = j


def group_end(toks, i):
    """toks[i] opens a delimited group; return the index just past its close."""
    lvl, j = 1, i + 1
    while j < len(toks) and lvl:
        t = toks[j][0]
        if t in OPEN:
            lvl += 1
        elif t in CLOSE:
            lvl -= 1
        j += 1
    if lvl:
        raise Problem("unbalanced delimiter in snippet")
    return j


class Elem:
    """One form of a binding vector: `x`, `[n ch1]`, `f(x)`, `#map{...}`."""
    __slots__ = ("text", "line", "col", "end_line", "end_col")

    def __init__(self, text, line, col, end_line, end_col):
        self.text, self.line, self.col = text, line, col
        self.end_line, self.end_col = end_line, end_col


def elements(toks, lines, i):
    """From toks[i] == '[' (a binding vector), return (elems, next_i).  Tokens
    that touch -- `f(x)`, `#map{...}`, `[]:int`, `#s"hi"`, `f(x)(y)` -- are one
    element: a token continues the element when it starts where the previous
    one ended."""
    elems = []
    i += 1
    while i < len(toks):
        tok, li, col, end = toks[i]
        if tok == "]":
            return elems, i + 1
        if tok in CLOSE:
            raise Problem("unbalanced delimiter in snippet")
        i = group_end(toks, i) if tok in OPEN else i + 1
        while i < len(toks) and toks[i][0] not in CLOSE and toks[i][1] == li \
                and toks[i][2] == toks[i - 1][3]:
            i = group_end(toks, i) if toks[i][0] in OPEN else i + 1
        last = toks[i - 1]
        text = lines[li][col:last[3]] if last[1] == li else lines[li][col:] + "..."
        prev = elems[-1] if elems else None
        if prev is not None and prev.text in BORROW_PREFIXES and prev.line == li:
            # `&mut x` is one value: the borrow prefix and its operand.
            prev.text = lines[li][prev.col:last[3]] if last[1] == li \
                else lines[li][prev.col:] + "..."
            prev.end_line, prev.end_col = last[1], last[3]
        else:
            elems.append(Elem(text, li, col, last[1], last[3]))
    raise Problem("binding vector never closes")


class Binding:
    """name .. value of one binding; `head_end` is the end column of whatever
    precedes the value (the name, or its `: type`)."""
    __slots__ = ("name", "head_end", "value")

    def __init__(self, name, head_end, value):
        self.name, self.head_end, self.value = name, head_end, value


def bindings(elems):
    """Group a vector's elements: [^meta ...] name [`:` type | :type] value.

    A keyword after the name (`x :int 1`) is read as its type only when
    another form follows on the same line; otherwise it is the value."""
    elems = [e for e in elems if e.text != "..."]
    out, i, n = [], 0, len(elems)
    while i < n:
        name = elems[i]
        while elems[i].text.startswith("^") and i + 1 < n:
            i += 1
        head_end = elems[i].end_col
        i += 1
        if i + 1 < n and elems[i].text == ":":
            head_end = elems[i + 1].end_col
            i += 2
        elif i + 1 < n and elems[i].text.startswith(":") and \
                len(elems[i].text) > 1 and elems[i + 1].line == name.line:
            head_end = elems[i].end_col
            i += 1
        if i >= n:
            raise Problem("odd number of forms in binding vector")
        out.append(Binding(name, head_end, elems[i]))
        i += 1
    return out


def vectors(lines):
    """Yield (head, line_idx, bindings) for every multi-line, multi-binding
    `let`-family vector in the snippet.  A vector the grammar cannot read
    (a sketch in a plan, a `]` inside a comment, an unfinished repro) is
    skipped: this is an alignment check, not a parser."""
    mask = inline_c_mask(lines)
    toks = list(tokenize(lines, mask))
    for i, (tok, li, col, _) in enumerate(toks):
        if tok != "[" or i == 0:
            continue
        head = toks[i - 1][0]
        if head not in FORMS:
            continue
        # `(let [` -- or sweet-exp `let [` at the head of its line.
        if not (i >= 2 and toks[i - 2][0] == "(") and \
           lines[toks[i - 1][1]][:toks[i - 1][2]].strip() not in ("", "$"):
            continue
        try:
            elems, _ = elements(toks, lines, i)
            pairs = bindings(elems)
        except Problem:
            continue
        if len(pairs) < 2 or len({e.line for e in elems}) == 1:
            continue
        yield head, li, pairs


# -- checking ----------------------------------------------------------------

def problems(pairs, head):
    """Messages for one vector: [] when it is aligned."""
    out = []
    split = [p for p in pairs if p.name.line != p.value.line]
    if split:
        p = split[0]
        return [(p.name.line, f"{head} binding `{p.name.text}` has its value on "
                 f"line {p.value.line + 1}; keep each binding on one line")]
    for prev, p in zip(pairs, pairs[1:]):
        if p.name.line == prev.name.line:
            return [(p.name.line, f"{head} binding `{p.name.text}` shares a line "
                     f"with `{prev.name.text}`; one binding per line")]
    first = pairs[0]
    odd = next((p for p in pairs if p.name.col != first.name.col), None)
    if odd:
        out.append((odd.name.line, f"{head} binding `{odd.name.text}` starts at "
                    f"column {odd.name.col + 1}, but `{first.name.text}` (line "
                    f"{first.name.line + 1}) starts at column {first.name.col + 1}"))
    odd = next((p for p in pairs if p.value.col != first.value.col), None)
    if odd:
        out.append((odd.name.line, f"{head} binding `{odd.name.text}`: value "
                    f"starts at column {odd.value.col + 1}, but `{first.name.text}`'s "
                    f"value (line {first.name.line + 1}) starts at column "
                    f"{first.value.col + 1}; pad the names so the values line up"))
    return out


def check_snippet(lines):
    """[(line_idx, message)] for every misaligned vector in the snippet."""
    report = []
    for head, li, pairs in vectors(lines):
        report += problems(pairs, head)
    return sorted(report + comment_problems(lines))


# -- fixing ------------------------------------------------------------------

def shift(line, delta):
    """Move a line's content by delta columns (left only through blanks)."""
    if delta >= 0:
        return " " * delta + line if line.strip() else line
    lead = len(line) - len(line.lstrip(" "))
    return line[min(-delta, lead):]


def fix_vector(lines, pairs):
    """Realign one vector in place.  Returns False when it cannot: a split
    binding, or two bindings on one line (moving one would drag the other,
    and the first binding's line is never moved).  Those are left alone."""
    if any(p.name.line != p.value.line for p in pairs):
        return False
    if len({p.name.line for p in pairs}) != len(pairs):
        return False
    # 1. Names: put every later binding's line under the first's column, and
    #    carry the lines that belong to it (its value's continuation, the
    #    comments and blanks before the next binding) with it.
    target = pairs[0].name.col
    for k, p in enumerate(pairs[1:], 1):
        delta = target - p.name.col
        if not delta:
            continue
        stop = pairs[k + 1].name.line if k + 1 < len(pairs) else p.value.end_line + 1
        for li in range(p.name.line, stop):
            lines[li] = shift(lines[li], delta)
        for q in pairs[k:]:
            if q.name.line < stop:
                for e in (q.name, q.value):
                    e.col += delta
                    e.end_col += delta
                q.head_end += delta
    # 2. Values: one column, just past the widest name (or `: type`).
    target = max(p.head_end + 1 for p in pairs)
    for p in pairs:
        delta = target - p.value.col
        if not delta:
            continue
        l = lines[p.value.line]
        lines[p.value.line] = l[:p.head_end] + " " * (target - p.head_end) + l[p.value.col:]
        for li in range(p.value.line + 1, p.value.end_line + 1):
            lines[li] = shift(lines[li], delta)
    return True


def fix_snippet(lines):
    """Realign every misaligned vector; vectors nested in a moved value are
    re-read on the next pass.  Returns the messages for what is left."""
    for _ in range(MAX_FIX_PASSES):
        changed = False
        for head, li, pairs in vectors(lines):
            if not problems(pairs, head):
                continue
            before = list(lines)
            if fix_vector(lines, pairs) and lines != before:
                changed = True
                break           # columns moved: re-tokenize before the next one
        if not changed:
            break
    fix_comments(lines)         # last: realigning values moves comments
    return check_snippet(lines)


# -- trailing comments ---------------------------------------------------------

def trailing_comment(line):
    """(code_end, col) for a line whose `;` comment starts at `col`: code_end
    is the end of the code before it, or None for a comment-only line.  None
    when the line has no comment.  Strings, `#\\;`, a `#;` datum comment and a
    one-line ```c ...``` span are not comments."""
    i, n, code_end = 0, len(line), None
    while i < n:
        c = line[i]
        if c == ";":
            return code_end, i
        if c == '"':
            i += 1
            while i < n and line[i] != '"':
                i += 2 if line[i] == "\\" else 1
            i += 1
        elif line.startswith("#\\", i):
            i += 3
        elif line.startswith("#;", i):
            i += 2                      # datum comment: the datum is code
        elif line.startswith("```", i):
            close = line.find("```", i + 3)
            if close < 0:
                return None
            i = close + 3
        elif c in " \t":
            i += 1
            continue
        else:
            i += 1
        code_end = min(i, n)
    return None


def multiline_mask(lines, skip):
    """True for each line that is in, or touches, a `#| ... |#` block comment
    (they nest) or a string that spans lines (a `#dedent` block): its `;` is
    text, not a trailing comment.  Lines in `skip` (inline C) are not read."""
    mask, depth, quote = [], 0, None
    for li, line in enumerate(lines):
        if skip[li]:
            mask.append(True)
            continue
        touched, i, n = depth > 0 or quote is not None, 0, len(line)
        while i < n:
            if quote:
                if line[i] == "\\":
                    i += 2
                elif line.startswith(quote, i):
                    quote, i = None, i + len(quote)
                else:
                    i += 1
            elif depth:
                if line.startswith("#|", i):
                    depth, i = depth + 1, i + 2
                elif line.startswith("|#", i):
                    depth, i = depth - 1, i + 2
                else:
                    i += 1
            elif line.startswith("#|", i):
                depth, touched, i = 1, True, i + 2
            elif line[i] == '"':
                quote = '"""' if line.startswith('"""', i) else '"'
                i += len(quote)
            elif line.startswith("#\\", i):
                i += 3
            elif line[i] == ";":
                break
            else:
                i += 1
        mask.append(touched or depth > 0 or quote is not None)
    return mask


def comment_runs(lines):
    """Runs of consecutive lines that each end in a comment after code, as
    [(line_idx, code_end, col)].  A comment-only line whose `;` sits right of
    the code above it continues that line's comment (code_end None) and moves
    with it; any other line ends the run."""
    mask = multiline_mask(lines, inline_c_mask(lines))
    runs, run = [], []
    for li, line in enumerate(lines):
        tc = None if mask[li] else trailing_comment(line)
        if tc and tc[0] is not None:
            run.append((li, tc[0], tc[1]))
            continue
        if tc and run and tc[0] is None and run[-1][1] is not None \
                and tc[1] > run[-1][1]:
            run.append((li, None, tc[1]))
            continue
        if sum(1 for m in run if m[1] is not None) > 1:
            runs.append(run)
        run = []
    if sum(1 for m in run if m[1] is not None) > 1:
        runs.append(run)
    return runs


def comment_target(run):
    """The column a run's comments belong in: the one most of its lines already
    use, the leftmost on a tie.  A line whose code reaches that column is
    exempt (see `overflows`): one long line does not push the others right."""
    cols = [m[2] for m in run if m[1] is not None]
    return max(set(cols), key=lambda c: (cols.count(c), -c))


def overflows(code_end, target):
    """A line too long for the run's column keeps its comment after its code."""
    return code_end is not None and code_end >= target


def comment_problems(lines):
    """[(line_idx, message)] for every trailing comment out of its run's column."""
    out = []
    for run in comment_runs(lines):
        target = comment_target(run)
        ref = next(m for m in run if m[2] == target)
        for li, code_end, col in run:
            if col != target and code_end is not None \
                    and not overflows(code_end, target):
                d = ref[0] - li
                where = f"{abs(d)} line{'s' * (abs(d) != 1)} {'below' if d > 0 else 'above'}"
                out.append((li, f"trailing comment starts at column {col + 1}, but "
                            f"the one {where} starts at column {target + 1}; "
                            "line up the comments of consecutive lines"))
    return out


def fix_comments(lines):
    """Move each misaligned run's comments to its column (whitespace only); a
    continuation line moves as far as the comment it continues."""
    for run in comment_runs(lines):
        target, delta = comment_target(run), 0
        for li, code_end, col in run:
            if code_end is None:
                lines[li] = shift(lines[li], delta)
                continue
            delta = 0 if overflows(code_end, target) else target - col
            if delta:
                lines[li] = lines[li][:code_end] + " " * (target - code_end) + lines[li][col:]


# -- driver ------------------------------------------------------------------

def check_file(path, fix):
    text = path.read_text(encoding="utf-8")
    out = []
    if path.suffix == ".md":
        all_lines = text.split("\n")
        for start, end, body, indent in fenced_snippets(text):
            if fix:
                report = fix_snippet(body)
                all_lines[start:end] = [indent + l if l.strip() else l for l in body]
            else:
                report = check_snippet(body)
            out += [(start + li + 1, msg) for li, msg in report]
        new_text = "\n".join(all_lines)
    else:
        body = text.split("\n")
        report = fix_snippet(body) if fix else check_snippet(body)
        out += [(li + 1, msg) for li, msg in report]
        new_text = "\n".join(body)
    if fix and new_text != text:
        path.write_text(new_text, encoding="utf-8")
        return out, True
    return out, False


def wanted(path):
    return path.suffix == ".md" or path.name.endswith(".tur") or \
        path.name.endswith(".tur.sweet")


