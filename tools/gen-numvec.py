# ---------------------------------------------------------------------------
# N1 -- bulk kernels, and N2 -- the unchecked accessors.
#
# Each kernel's C body is written ONCE, here.  It becomes the inline-C body of
# the stdlib function, and the same text is compiled into the interpreter's
# native for it (src/turi/numvec_kernels.inc), so the two engines run the same
# arithmetic in the same order and agree bit for bit.
#
# Rules every body keeps (simd-and-vectorization-plan N1):
#   - any panic (a length mismatch, an empty min/max) comes before the loop, so
#     the loop has no control flow and gcc vectorizes it at -O3;
#   - a float reduction accumulates into EIGHT interleaved partial results
#     (lane k takes the elements i with i mod 8 = k) and combines them in one
#     fixed tree -- the reassociation -ffast-math would make, chosen here, the
#     same on every engine and ISA.  `-sum-ordered` is the strict left fold;
#   - a multiply and the add that consumes it are separate statements, so no
#     compiler contracts them into an FMA (clang contracts within one
#     expression; gcc does not in the ISO mode tur compiles in);
#   - integer arithmetic wraps (it is done in the unsigned type), never UB.
# ---------------------------------------------------------------------------

HDRV = "struct {{ int64_t len; {C} *data; void *raw; }} *{n} = (void*)(intptr_t){v};"


def hdr(t, n, v):
    return HDRV.format(C=t["C"], n=n, v=v)


IS_FLOAT = {"f64vec": True, "f32vec": True, "i64vec": False, "i32vec": False,
            "u8vec": False}
# the unsigned type integer arithmetic wraps in
UNS = {"i64vec": "uint64_t", "i32vec": "uint32_t", "u8vec": "uint8_t"}


def same_len(t, name, ret):
    return ("if (y->len != x->len) {\n"
            "    tur_panic(\"%s-%s: length mismatch\");\n"
            "    return%s;\n"
            "  }") % (t["p"], name, ret)


# How a loop is spelled is chosen by measurement (simd-and-vectorization-plan
# N2, "closing the -O2 gap"), never by taste:
#   - `unrolled`: the main loop's body is the eight steps written out.  gcc's
#     default -O2 vectorizes no loop whose trip count it cannot see, and only
#     -O3 unrolls an inner lane loop itself; written out, the body is
#     straight-line code its basic-block vectorizer takes at -O2.  2-5x at
#     -O2, and as fast as before at -O3.
#   - `by_compiler`: clang vectorizes the plain loop at -O2 already, and runs
#     the written-out body of `add!` / `scale!` / `axpy!` / integer `min` /
#     `max` slower (with two arrays it cannot prove the written-out stores do
#     not overlap the loads), so it keeps the loop.
#   - `unrolled_scalar_lanes` (float `dot`): accumulators as eight scalars
#     and a written-out tail, so clang pairs adjacent lanes (see the helper).
#   - float `min` / `max`: eight scalar lanes written out, NaN detected by a
#     running sum beside them (see k_minmax).  gcc vectorizes no float min
#     reduction without -ffast-math; these scalar chains still beat the
#     spelling it did vectorize.
#   Every spelling computes the same element-by-element arithmetic, so the
#   result is the same either way.

def idx(k):
    return "i" if k == 0 else "i + %d" % k


def unrolled(step, tail):
    """`step(index_expr, lane)` -> one C statement; `tail` covers i..n-1."""
    return (["int64_t i = 0;", "for (; i + 8 <= n; i += 8) {"]
            + ["  " + step(idx(k), k) for k in range(8)]
            + ["}", "for (; i < n; i++) " + tail])


def unrolled_loads_first(loads, computes, stores, tail):
    """The eight-wide body as all loads, then all arithmetic, then all stores.
    With two arrays gcc's -O2 basic-block vectorizer cannot reorder a store
    past a load it cannot prove independent; written in this order nothing
    needs reordering, and it vectorizes (2x on `add!` / `axpy!`).  Each
    argument maps (index_expr, lane) to a statement, or is None."""
    body = []
    for part in (loads, computes, stores):
        if part:
            body += ["  " + part(idx(k), k) for k in range(8)]
    return (["int64_t i = 0;", "for (; i + 8 <= n; i += 8) {"] + body
            + ["}", "for (; i < n; i++) " + tail])


def unrolled_scalar_lanes(C, step):
    """Eight accumulators as scalars `s0`..`s7`, not an array, with the tail
    written out as seven guarded steps: element i + k still lands in lane k,
    so the arithmetic is the array form's.  `step(index_expr, lane_var)` ->
    one C statement.  For `dot`: with `s[8]` and a `s[i & 7]` tail clang
    pairs lane 0 with lane 4 (1 with 5, ...) and assembles every vector from
    two half loads -- 0.31s against 0.17s for this spelling, gcc unchanged."""
    return (["%s %s;" % (C, ", ".join("s%d = 0" % k for k in range(8))),
             "int64_t i = 0;", "for (; i + 8 <= n; i += 8) {"]
            + ["  " + step(idx(k), "s%d" % k) for k in range(8)]
            + ["}"]
            + ["if (%s < n) %s" % (idx(k), step(idx(k), "s%d" % k)) for k in range(7)])


SCALAR_TREE = "((s0 + s1) + (s2 + s3)) + ((s4 + s5) + (s6 + s7))"


def by_compiler(loop_lines, hand_lines):
    return (["/* clang vectorizes the plain loop; gcc -O2 only the written-out body */",
             "#if defined(__clang__)"] + loop_lines + ["#else"] + hand_lines + ["#endif"])


def k_fill(t):
    return "\n".join([hdr(t, "a", "v"), "int64_t n = a->len;",
                      "%s *d = a->data;" % t["C"]]
                     + unrolled(lambda j, k: "d[%s] = x;" % j, "d[i] = x;"))


def k_copy(t):
    return "\n".join([hdr(t, "y", "dst"), hdr(t, "x", "src"),
                      same_len(t, "copy!", ""),
                      "if (y->len > 0) memmove(y->data, x->data, (size_t)y->len * sizeof(%s));" % t["C"]])


def k_scale(t):
    C = t["C"]
    if IS_FLOAT[t["p"]]:
        op = lambda j: "d[%s] = d[%s] * s;" % (j, j)
    else:
        U = UNS[t["p"]]
        op = lambda j: "d[%s] = (%s)((%s)d[%s] * (%s)s);" % (j, C, U, j, U)
    return "\n".join([hdr(t, "a", "v"), "int64_t n = a->len;", "%s *d = a->data;" % C]
                     + by_compiler(["for (int64_t i = 0; i < n; i++) " + op("i")],
                                   unrolled(lambda j, k: op(j), op("i"))))


def k_binop(t, name, opc):
    """dst[i] = dst[i] <opc> src[i] -- `add!`, `sub!`, `mul!`."""
    C = t["C"]
    if IS_FLOAT[t["p"]]:
        op = lambda j: "yd[%s] = yd[%s] %s xd[%s];" % (j, j, opc, j)
        st = lambda j, k: "yd[%s] = y%d %s x%d;" % (j, k, opc, k)
    else:
        U = UNS[t["p"]]
        op = lambda j: "yd[%s] = (%s)((%s)yd[%s] %s (%s)xd[%s]);" % (j, C, U, j, opc, U, j)
        st = lambda j, k: "yd[%s] = (%s)((%s)y%d %s (%s)x%d);" % (j, C, U, k, opc, U, k)
    ld = lambda j, k: "%s y%d = yd[%s], x%d = xd[%s];" % (C, k, j, k, j)
    return "\n".join([hdr(t, "y", "dst"), hdr(t, "x", "src"),
                      same_len(t, name, ""),
                      "int64_t n = y->len;",
                      "%s *yd = y->data;" % C, "const %s *xd = x->data;" % C]
                     + by_compiler(["for (int64_t i = 0; i < n; i++) " + op("i")],
                                   unrolled_loads_first(ld, None, st, op("i"))))


def k_add(t):
    return k_binop(t, "add!", "+")


def k_add_scalar(t):
    """v[i] = v[i] + s, spelled as `scale!` is."""
    C = t["C"]
    if IS_FLOAT[t["p"]]:
        op = lambda j: "d[%s] = d[%s] + s;" % (j, j)
    else:
        U = UNS[t["p"]]
        op = lambda j: "d[%s] = (%s)((%s)d[%s] + (%s)s);" % (j, C, U, j, U)
    return "\n".join([hdr(t, "a", "v"), "int64_t n = a->len;", "%s *d = a->data;" % C]
                     + by_compiler(["for (int64_t i = 0; i < n; i++) " + op("i")],
                                   unrolled(lambda j, k: op(j), op("i"))))


def k_axpy(t):
    C = t["C"]
    ld = lambda j, k: "%s y%d = yd[%s], x%d = xd[%s];" % (C, k, j, k, j)
    if IS_FLOAT[t["p"]]:
        op = lambda j: "{ %s m = s * xd[%s]; yd[%s] = yd[%s] + m; }" % (C, j, j, j)
        cp = lambda j, k: "%s m%d = s * x%d;" % (C, k, k)
        st = lambda j, k: "yd[%s] = y%d + m%d;" % (j, k, k)
    else:
        U = UNS[t["p"]]
        op = lambda j: "{ %s m = (%s)s * (%s)xd[%s]; yd[%s] = (%s)((%s)yd[%s] + m); }" % (
            U, U, U, j, j, C, U, j)
        cp = lambda j, k: "%s m%d = (%s)s * (%s)x%d;" % (U, k, U, U, k)
        st = lambda j, k: "yd[%s] = (%s)((%s)y%d + m%d);" % (j, C, U, k, k)
    return "\n".join([hdr(t, "y", "dst"), hdr(t, "x", "src"),
                      same_len(t, "axpy!", ""),
                      "int64_t n = y->len;",
                      "%s *yd = y->data;" % C, "const %s *xd = x->data;" % C]
                     + by_compiler(["for (int64_t i = 0; i < n; i++) " + op("i")],
                                   unrolled_loads_first(ld, cp, st, op("i"))))


TREE = "((s[0] + s[1]) + (s[2] + s[3])) + ((s[4] + s[5]) + (s[6] + s[7]))"


def k_sum(t):
    C = t["C"]
    if IS_FLOAT[t["p"]]:
        return "\n".join([hdr(t, "a", "v"), "int64_t n = a->len;",
                          "const %s *d = a->data;" % C,
                          "%s s[8] = {0, 0, 0, 0, 0, 0, 0, 0};" % C]
                         + unrolled(lambda j, k: "s[%d] = s[%d] + d[%s];" % (k, k, j),
                                    "s[i & 7] = s[i & 7] + d[i];")
                         + ["return %s;" % TREE])
    if t["p"] == "u8vec":
        # 32-bit lanes (a byte widens to 64 bits poorly), flushed into the
        # 64-bit total every 2^24 elements: 8 lanes x 2^21 x 255 < 2^32
        return "\n".join([hdr(t, "a", "v"), "int64_t n = a->len;",
                          "const %s *d = a->data;" % C,
                          "uint64_t total = 0;", "int64_t i = 0;",
                          "while (i + 8 <= n) {",
                          "  int64_t stop = n - i < ((int64_t)1 << 24) ? n : i + ((int64_t)1 << 24);",
                          "  uint32_t s[8] = {0, 0, 0, 0, 0, 0, 0, 0};",
                          "  for (; i + 8 <= stop; i += 8) {"]
                         + ["    s[%d] = s[%d] + (uint32_t)d[%s];" % (k, k, idx(k)) for k in range(8)]
                         + ["  }",
                            "  total = total + ((((uint64_t)s[0] + s[1]) + ((uint64_t)s[2] + s[3]))",
                            "                 + (((uint64_t)s[4] + s[5]) + ((uint64_t)s[6] + s[7])));",
                            "}",
                            "for (; i < n; i++) total = total + (uint64_t)d[i];",
                            "return (int64_t)total;"])
    # exact modulo 2^64, so the eight lanes give the same answer as one
    wid = "(uint64_t)(int64_t)" if t["p"] == "i32vec" else "(uint64_t)"
    return "\n".join([hdr(t, "a", "v"), "int64_t n = a->len;",
                      "const %s *d = a->data;" % C,
                      "uint64_t s[8] = {0, 0, 0, 0, 0, 0, 0, 0};"]
                     + unrolled(lambda j, k: "s[%d] = s[%d] + %sd[%s];" % (k, k, wid, j),
                                "s[i & 7] = s[i & 7] + %sd[i];" % wid)
                     + ["return (int64_t)(%s);" % TREE])


def k_sum_ordered(t):
    C = t["C"]
    return "\n".join([hdr(t, "a", "v"), "int64_t n = a->len;",
                      "const %s *d = a->data;" % C, "%s s = 0;" % C,
                      "for (int64_t i = 0; i < n; i++) s = s + d[i];",
                      "return s;"])


def k_dot(t):
    C = t["C"]
    pre = [hdr(t, "y", "a"), hdr(t, "x", "b"),
           same_len(t, "dot", " 0"),
           "int64_t n = y->len;",
           "const %s *yd = y->data;" % C, "const %s *xd = x->data;" % C]
    if IS_FLOAT[t["p"]]:
        return "\n".join(pre
                         + unrolled_scalar_lanes(C, lambda j, s: "{ %s m = yd[%s] * xd[%s]; %s = %s + m; }"
                                                 % (C, j, j, s, s))
                         + ["return %s;" % SCALAR_TREE])
    if t["p"] == "i32vec":
        prod = lambda j: "(uint64_t)((int64_t)yd[%s] * (int64_t)xd[%s])" % (j, j)
    else:
        prod = lambda j: "(uint64_t)yd[%s] * (uint64_t)xd[%s]" % (j, j)
    return "\n".join(pre + ["uint64_t s[8] = {0, 0, 0, 0, 0, 0, 0, 0};"]
                     + unrolled(lambda j, k: "s[%d] = s[%d] + %s;" % (k, k, prod(j)),
                                "s[i & 7] = s[i & 7] + %s;" % prod("i"))
                     + ["return (int64_t)(%s);" % TREE])


def k_minmax(t, which):
    C = t["C"]
    op = "<" if which == "min" else ">"
    pre = [hdr(t, "a", "v"), "int64_t n = a->len;",
           "if (n == 0) {",
           '    tur_panic("%s-%s: empty array");' % (t["p"], which),
           "    return 0;", "  }",
           "const %s *d = a->data;" % C]
    if IS_FLOAT[t["p"]]:
        # A NaN anywhere makes the result NaN: the FIRST NaN by index.  The
        # lanes are a plain `x OP m ? x : m` -- one SSE min/max instruction,
        # with no -ffast-math -- which never lets a NaN in, so NaN is found
        # apart from them: a running sum of the elements is NaN when any of
        # them is, and only then does a second pass find the first one.  (It
        # is also NaN for an array holding both infinities, or one whose sum
        # overflows to both; the second pass then finds none and the lanes
        # answer.)  The sum is the cheapest detector there is -- one add per
        # element, two chains -- and it keeps the eight lanes and their temps
        # within sixteen registers; a per-lane int flag cost gcc twice the
        # time (0.37s against 0.24s, benchmarks/f64vec-dot-results.md).
        ms = ["m%d" % k for k in range(8)]
        xs = ["x%d" % k for k in range(8)]
        return "\n".join(pre + [
            "%s %s;" % (C, ", ".join("%s = d[0]" % m for m in ms)),
            "%s z0 = 0, z1 = 0;" % C,
            "int64_t i = 0;",
            "for (; i + 8 <= n; i += 8) {",
            "  %s %s;" % (C, ", ".join("x%d = d[%s]" % (k, idx(k)) for k in range(8)))]
            + ["  %s = %s %s %s ? %s : %s;" % (ms[k], xs[k], op, ms[k], xs[k], ms[k])
               for k in range(8)]
            + ["  %s p0 = (x0 + x2) + (x4 + x6);" % C,
               "  %s p1 = (x1 + x3) + (x5 + x7);" % C,
               "  z0 = z0 + p0;",
               "  z1 = z1 + p1;",
               "}",
               "%s m[8] = {%s};" % (C, ", ".join(ms)),
               "%s z = z0 + z1;" % C,
               "for (; i < n; i++) {",
               "  %s x = d[i];" % C,
               "  m[i & 7] = x %s m[i & 7] ? x : m[i & 7];" % op,
               "  z = z + x;",
               "}",
               "if (z != z) {",
               "  for (int64_t j = 0; j < n; j++) if (d[j] != d[j]) return d[j];",
               "}",
               "for (int w = 4; w >= 1; w /= 2)",
               "  for (int k = 0; k < w; k++) m[k] = m[k + w] %s m[k] ? m[k + w] : m[k];" % op,
               "return m[0];"])
    hand = (["%s m[8];" % C, "for (int k = 0; k < 8; k++) m[k] = d[0];"]
            + unrolled(lambda j, k: "m[%d] = d[%s] %s m[%d] ? d[%s] : m[%d];" % (k, j, op, k, j, k),
                       "m[i & 7] = d[i] %s m[i & 7] ? d[i] : m[i & 7];" % op)
            + ["for (int w = 4; w >= 1; w /= 2)",
               "  for (int k = 0; k < w; k++) m[k] = m[k + w] %s m[k] ? m[k + w] : m[k];" % op,
               "return m[0];"])
    loop = ["%s m = d[0];" % C,
            "for (int64_t i = 1; i < n; i++) m = d[i] %s m ? d[i] : m;" % op,
            "return m;"]
    return "\n".join(pre + by_compiler(loop, hand))


