MACROS = r''';;; {p}-for -- run body once per element of one or two {T}s.
;;;
;;; `(for [x v] body...)` binds x to each element of v in order;
;;; `(for [x v y w] body...)` walks v and w together (same length, or a panic
;;; before the first pass).  No index is in scope, so none can be wrong: the
;;; reads are `{p}-ref-unchecked`, the body sees plain elements, and the loop
;;; carries no bounds check or panic test -- gcc can vectorize it at -O3.  An
;;; array argument that is not a name is evaluated once, and freed after.
;;;
;;; Parameters:
;;;   bindings -- `[x v]` or `[x v y w]`
;;;   body     -- the forms to run per element
;;;
;;; Example:
;;;   (let [v ({p}-of {e0} {e1})] ({p}-for [x v] (println x)))
;;;
;;; Since: Phase N2

(defmacro {p}-for [bv & body]
  (let [i    (gensym "i")
        n    (gensym "n")
        x    (first bv)
        v    (second bv)
        more (rest (rest bv))]
    (if (list? v)
      (let [t (gensym "nv")]
        `(let [~t ~v] ({p}-for [~x ~t ~@more] ~@body)))
      (if (empty? more)
        `(let [^mut ~i 0
               ~n      ({p}-len ~v)]
           (while (< ~i ~n)
             (let [~x (unsafe ({p}-ref-unchecked ~v ~i))]
               ~@body)
             (set! ~i (+ ~i 1))))
        (let [y (first more)
              w (second more)]
          (if (list? w)
            (let [t (gensym "nv")]
              `(let [~t ~w] ({p}-for [~x ~v ~y ~t] ~@body)))
            `(let [^mut ~i 0
                   ~n      ({p}-same-len__ ~v ~w)]
               (while (< ~i ~n)
                 (let [~x (unsafe ({p}-ref-unchecked ~v ~i))
                       ~y (unsafe ({p}-ref-unchecked ~w ~i))]
                   ~@body)
                 (set! ~i (+ ~i 1))))))))))
;;; {p}-for-index -- run body once per element, with its index.
;;;
;;; `(for-index [i x v] body...)` binds i (read-only) and x = v[i].
;;;
;;; Parameters:
;;;   bindings -- `[i x v]`
;;;   body     -- the forms to run per element
;;;
;;; Example:
;;;   (let [v ({p}-of {e0} {e1})] ({p}-for-index [i x v] (println i)))
;;;
;;; Since: Phase N2

(defmacro {p}-for-index [bv & body]
  (let [i  (gensym "i")
        n  (gensym "n")
        iv (first bv)
        x  (second bv)
        v  (first (rest (rest bv)))]
    (if (list? v)
      (let [t (gensym "nv")]
        `(let [~t ~v] ({p}-for-index [~iv ~x ~t] ~@body)))
      `(let [^mut ~i 0
             ~n      ({p}-len ~v)]
         (while (< ~i ~n)
           (let [~iv ~i
                 ~x  (unsafe ({p}-ref-unchecked ~v ~i))]
             ~@body)
           (set! ~i (+ ~i 1)))))))
;;; {p}-fold -- fold the elements of a {T} into an accumulator.
;;;
;;; `(fold [acc init x v] body)`: acc starts at init, and for each element x
;;; in order becomes the value of body (which sees acc and x).  The result is
;;; the final acc.  A float sum written this way is the strict left fold, so
;;; gcc keeps it scalar; `{p}-sum` is the vectorized one.
;;;
;;; Parameters:
;;;   bindings -- `[acc init x v]`
;;;   body     -- the new accumulator
;;;
;;; Returns:
;;;   The final accumulator.
;;;
;;; Example:
;;;   (let [v ({p}-of {e0} {e1})] ({p}-fold [n 0 x v] (+ n 1)))   ; => 2
;;;
;;; Since: Phase N2

(defmacro {p}-fold [bv body]
  (let [i    (gensym "i")
        n    (gensym "n")
        acc  (first bv)
        init (second bv)
        x    (first (rest (rest bv)))
        v    (second (rest (rest bv)))]
    (if (list? v)
      (let [t (gensym "nv")]
        `(let [~t ~v] ({p}-fold [~acc ~init ~x ~t] ~body)))
      `(let [^mut ~i   0
             ~n        ({p}-len ~v)
             ^mut ~acc ~init]
         (while (< ~i ~n)
           (let [~x (unsafe ({p}-ref-unchecked ~v ~i))]
             (set! ~acc ~body))
           (set! ~i (+ ~i 1)))
         ~acc))))
;;; {p}-build -- a fresh {T} of n elements, element i the value of expr.
;;;
;;; `(build n [i] expr)`, after Racket's `for/flvector`: i is bound to each
;;; index in turn, and expr runs outside any `unsafe`.  The stores go through a
;;; view (`{p}-view`), so the loop vectorizes where expr allows: at -O2 under
;;; clang, at -O3 (`--release`) under gcc.
;;;
;;; Parameters:
;;;   n    -- the length (evaluated once)
;;;   i    -- the index name, in a vector
;;;   expr -- the element at i, of type {E}
;;;
;;; Returns:
;;;   A fresh {T}, owned by the caller.
;;;
;;; Example:
;;;   (let [v ({p}-build 3 [i] {e0})] ({p}-len v))   ; => 3
;;;
;;; Since: Phase N2

(defmacro {p}-build [n bv expr]
  (let [i   (gensym "i")
        m   (gensym "n")
        e   (gensym "e")
        out (gensym "out")
        w   (gensym "w")
        iv  (first bv)]
    `(let [~m      ~n
           ~out    ({p}-new ~m %ZERO%)
           ~w      (unsafe ({p}-view ~out))
           ^mut ~i 0]
       (while (< ~i ~m)
         (let [~iv ~i
               ~e  ~expr]
           (unsafe ({p}-view-set! ~w ~i ~e)))
         (set! ~i (+ ~i 1)))
       ~out)))
;;; {p}-map! -- store expr into dst[i] for every i, x bound to src[i].
;;;
;;; `(map! dst [x src] expr)` stores into each slot of dst the value of expr
;;; with x bound to the element of src at the same index; `(map! dst [x a y b]
;;; expr)` walks two sources together.  dst may be one of the sources:
;;; `(map! v [x v] {{x * 2}})` maps in place.  Every array has the same length,
;;; or a panic before the first element.  The loop reads and stores through
;;; views (`{p}-view`), so it vectorizes where expr allows: at -O2 under clang,
;;; at -O3 (`--release`) under gcc.  expr runs outside any `unsafe`; an array
;;; argument that is not a name is evaluated once, and freed after the loop.
;;;
;;; Parameters:
;;;   dst      -- the array stored into (borrowed)
;;;   bindings -- `[x src]` or `[x a y b]`
;;;   expr     -- the new element, of type {E}
;;;
;;; Example:
;;;   (let [v ({p}-of {e0} {e1})] ({p}-map! v [x v] x) ({p}-ref v 1))   ; => {e1}
;;;
;;; Since: Phase N2

(defmacro {p}-map! [dst bv expr]
  (let [i    (gensym "i")
        n    (gensym "n")
        e    (gensym "e")
        wd   (gensym "wd")
        wa   (gensym "wa")
        wb   (gensym "wb")
        x    (first bv)
        a    (second bv)
        more (rest (rest bv))]
    (if (list? dst)
      (let [t (gensym "nv")]
        `(let [~t ~dst] ({p}-map! ~t ~bv ~expr)))
      (if (list? a)
        (let [t (gensym "nv")]
          `(let [~t ~a] ({p}-map! ~dst [~x ~t ~@more] ~expr)))
        (if (empty? more)
          `(let [~n      ({p}-same-len__ ~dst ~a)
                 ~wd     (unsafe ({p}-view ~dst))
                 ~wa     (unsafe ({p}-view ~a))
                 ^mut ~i 0]
             (while (< ~i ~n)
               (let [~x (unsafe ({p}-view-ref ~wa ~i))
                     ~e ~expr]
                 (unsafe ({p}-view-set! ~wd ~i ~e)))
               (set! ~i (+ ~i 1))))
          (let [y (first more)
                b (second more)]
            (if (list? b)
              (let [t (gensym "nv")]
                `(let [~t ~b] ({p}-map! ~dst [~x ~a ~y ~t] ~expr)))
              `(let [~n      (do ({p}-same-len__ ~a ~b) ({p}-same-len__ ~dst ~a))
                     ~wd     (unsafe ({p}-view ~dst))
                     ~wa     (unsafe ({p}-view ~a))
                     ~wb     (unsafe ({p}-view ~b))
                     ^mut ~i 0]
                 (while (< ~i ~n)
                   (let [~x (unsafe ({p}-view-ref ~wa ~i))
                         ~y (unsafe ({p}-view-ref ~wb ~i))
                         ~e ~expr]
                     (unsafe ({p}-view-set! ~wd ~i ~e)))
                   (set! ~i (+ ~i 1)))))))))))
;;; {p}-same-len__ -- internal: the common length of two arrays, or a panic.

(defn {p}-same-len__ [^borrow a : {T} ^borrow b : {T}]
  #fx{{}}
  #reads [a b]
  : int
  ```c
  struct {{ int64_t len; {C} *data; void *raw; }} *x = (void*)(intptr_t)a;
  struct {{ int64_t len; {C} *data; void *raw; }} *y = (void*)(intptr_t)b;
  if (x->len != y->len) {{
    tur_panic("{p}-for: length mismatch");
    return 0;
  }}
  return x->len;
  ```)
'''


