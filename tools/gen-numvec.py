#!/usr/bin/env python3
"""gen-numvec.py -- generate stdlib/numvec.tur.

The five typed numeric arrays of docs/upcoming/simd-and-vectorization-plan.md
(phase N0) are the same code five times over a different C element type, so
the module is generated from one template.  Edit the template here, then:

    python3 tools/gen-numvec.py > stdlib/numvec.tur

`python3 tools/gen-numvec.py --check` exits 1 if stdlib/numvec.tur is stale.
Every inline-C body -- `<p>-new`, `-free`, `-copy`, `-len`, `-ref`, `-set!` --
has an interpreter twin of the same name in src/turi/interpreter_natives.c
(NUMVEC_NATIVES) and rows in src/turi/native_caps.c; keep all three in step.
"""
import os
import sys

# p: prefix, T: type, E: element type, C: C element, zero: a literal of E,
# zm: the same zero as a macro-time `list` form, ex/exs: docstring examples.
TYPES = [
    dict(p="f64vec", T="F64Vec", E="float", C="double",
         zero="0.0", zm="0.0", ex=("1.5", "2.5"), exs="7.1",
         what="64-bit floats"),
    dict(p="f32vec", T="F32Vec", E="float32", C="float",
         zero="(as float32 0.0)", zm="(list as float32 0.0)",
         ex=("(:: 1.5 float32)", "(:: 2.5 float32)"), exs="(:: 3.25 float32)",
         what="32-bit floats"),
    dict(p="i64vec", T="I64Vec", E="int", C="int64_t",
         zero="0", zm="0", ex=("1", "2"), exs="7",
         what="64-bit integers"),
    dict(p="i32vec", T="I32Vec", E="int32", C="int32_t",
         zero="(as int32 0)", zm="(list as int32 0)",
         ex=("(as int32 1)", "(as int32 2)"), exs="(as int32 7)",
         what="32-bit integers"),
    dict(p="u8vec", T="U8Vec", E="uint8", C="uint8_t",
         zero="(as uint8 0)", zm="(list as uint8 0)",
         ex=("(as uint8 1)", "(as uint8 2)"), exs="(as uint8 200)",
         what="bytes"),
]

HDR = """;;; tur/numvec -- typed numeric arrays: F64Vec, F32Vec, I64Vec, I32Vec, U8Vec.
;;;
;;; GENERATED by tools/gen-numvec.py -- edit the template there, not this file.
;;;
;;; A fixed-length, homogeneous, unboxed array of one numeric element type, in
;;; the manner of Racket's `flvector`.  Each type is its own opaque handle over
;;; one C layout:
;;;
;;; ```c
;;; struct { int64_t len; T *data; void *raw; }   /* T = double, float, ... */
;;; ```
;;;
;;; `data` is 32-byte aligned (`raw` is the malloc block it was carved from,
;;; and what `free` is given), so an aligned SIMD load is legal on it and gcc
;;; can skip its peeling prologue.  The element is its real width: a `U8Vec`
;;; uses one byte a slot, not eight as a `Vec` does.
;;;
;;; | Type   | Element   | Constructor               |
;;; |--------|-----------|---------------------------|
;;; | F64Vec | `float`   | `(f64vec-new n init)`     |
;;; | F32Vec | `float32` | `(f32vec-new n init)`     |
;;; | I64Vec | `int`     | `(i64vec-new n init)`     |
;;; | I32Vec | `int32`   | `(i32vec-new n init)`     |
;;; | U8Vec  | `uint8`   | `(u8vec-new n init)`      |
;;;
;;; Every type has the same nine operations, named by its prefix `P` (`f64vec`,
;;; `f32vec`, `i64vec`, `i32vec`, `u8vec`):
;;; `P-new`, `P-of`, `P-len`, `P-ref`, `P-set!`, `P-copy`, `P->vec`,
;;; `vec->P`, `P-show`.
;;;
;;; Ownership: each type is `^affine` with a `Drop` instance, so a let-bound
;;; array is freed at scope exit, exactly once, and moving it (returning it,
;;; passing it to a consumer) hands that duty on.  The accessors take it
;;; `^borrow`.  `P-free` consumes an array early.
;;;
;;; A temporary handed straight to an accessor that returns a number --
;;; `(f64vec-len (f64vec-new 4 0.0))` -- is freed after the call.  One handed to
;;; anything else (`P-copy`, `P->vec`, `P-show`, or after an argument with side
;;; effects) has no owner and is not freed, so bind it first:
;;; `(let [v (f64vec-new 4 0.0)] (f64vec-show v))`
;;; (docs/reported/borrowed-drop-temporary-leaks-outside-the-hoist.md).
;;;
;;; A closure that captures an array the enclosing scope OWNS takes it over
;;; (the scope can no longer use it, and the closure frees it); one that
;;; captures a `^borrow` parameter borrows it, and frees nothing.
;;;
;;; Length is fixed at construction.  Growth stays `Vec`'s job; `P->vec` and
;;; `vec->P` convert.  An index outside `[0, len)` panics, at the caller's
;;; line, on every engine.
;;;
;;; Region stores: an element store writes a number, never a pointer, so the
;;; setters carry no TUR_REGION_NOTE (CLAUDE.md, "Region Store Hooks" covers a
;;; caller's word that can outlive a bracket -- a pointer).
;;;
;;; Since: Phase N0 (simd-and-vectorization-plan)
(load "stdlib/typeclass.tur")

;;; numvec-of__ -- internal: the flat body of every `P-of`.
;;;
;;; `(numvec-of__ new set! zero v x0 x1 ...)` expands to
;;; `(let [v (new n zero)] (do (set! v 0 x0) (set! v 1 x1) ... v))`.  A
;;; procedural macro, so it counts its arguments and emits one flat body: a
;;; template macro recurses once per element and stops at the 256-deep
;;; expansion limit.  `v` comes from the caller, minted there with `(gensym)`,
;;; which is fresh against the program's own names (`syntax-gensym` here is
;;; fresh only against the macro-time env's).

(defmacro* numvec-of__ [new setter zero v & xs]
  (let [n (syntax-len xs)]
    (letrec [sets (fn [i : int acc : Syntax] : Syntax
                    (if (< i 0)
                      acc
                      (sets (- i 1)
                            (syntax-cons `(~setter ~v ~(int->syntax i) ~(syntax-nth xs i)) acc))))]
      (let [mk   `(~new ~(int->syntax n) ~zero)
            bind (syntax-vec v mk)
            body (syntax-cons (sym->syntax "do") (sets (- n 1) (syntax-list v)))]
        `(let ~bind ~body)))))
"""

TEMPLATE = r""";; ===== {T}: {what} =====
;;; {T} -- a fixed-length, unboxed array of {what} ({E}).
;;;
;;; Opaque handle to a `struct {{ int64_t len; {C} *data; void *raw; }}`.
;;; `^affine`: freed at scope exit by its `Drop` instance.  Use `{p}-new` or
;;; `{p}-of` to make one.
;;;
;;; Since: Phase N0
(defopaque ^affine {T} :int)
;; Every operation that touches the header is an inline-C body of its own,
;; never a Turmeric wrapper over a raw one, so a panic is reported at the
;; CALLER's line (as vec-get's is) and turi's natives are keyed by the public
;; names.  An element store writes a number, never a pointer, so the setter
;; carries no TUR_REGION_NOTE (CLAUDE.md, "Region Store Hooks").
;;; {p}-new -- allocate a {T} of n elements, every one init.
;;;
;;; Parameters:
;;;   n    -- element count (>= 0; a negative or absurd n panics)
;;;   init -- the value every slot starts with
;;;
;;; Returns:
;;;   A fresh {T}, owned by the caller and freed at scope exit.
;;;
;;; Example:
;;;   (let [v ({p}-new 4 {exs})]
;;;     ({p}-ref v 2))   ; => {exs}
;;;
;;; Since: Phase N0

(defn {p}-new [n : int init : {E}]
  #fx{{}}
  : {T}
  ```c
  /* the data block is 32-byte aligned; n * sizeof wrapped for a huge n would
     leave a tiny block under a huge recorded len, so the bound is explicit. */
  if (n < 0 || (uint64_t)n > (SIZE_MAX - 64) / sizeof({C})) {{
    tur_panic("{p}-new: length out of range");
    return 0;
  }}
  struct {{ int64_t len; {C} *data; void *raw; }} *b = malloc(sizeof(*b));
  if (!b) {{ fprintf(stderr, "{p}-new: out of memory\n"); abort(); }}
  b->len = n;
  b->raw = malloc((size_t)n * sizeof({C}) + 32);
  if (!b->raw) {{ fprintf(stderr, "{p}-new: out of memory\n"); abort(); }}
  b->data = ({C} *)(((uintptr_t)b->raw + 31) & ~(uintptr_t)31);
  for (int64_t i = 0; i < n; i++) b->data[i] = init;
  return (int64_t)(intptr_t)b;
  ```)
;;; {p}-of -- a {T} holding the given elements, in order.
;;;
;;; Parameters:
;;;   & xs -- zero or more elements of type {E}
;;;
;;; Returns:
;;;   A fresh {T} of length (count xs).
;;;
;;; Example:
;;;   (let [v ({p}-of {e0} {e1})]
;;;     ({p}-len v))   ; => 2
;;;
;;; Since: Phase N0

(defmacro {p}-of [& xs]
  (let [v (gensym "nv")]
    (list numvec-of__ {p}-new {p}-set! {zm} v ~@xs)))
;;; {p}-free -- release a {T} now, consuming it.
;;;
;;; Rarely needed: a let-bound {T} is freed at scope exit.  Call it to
;;; release a large array before the scope ends.
;;;
;;; Parameters:
;;;   v -- the array (consumed)
;;;
;;; Example:
;;;   ({p}-free v)
;;;
;;; Since: Phase N0

(defn {p}-free [v : {T}]
  #fx{{}}
  : nil
  ```c
  struct {{ int64_t len; {C} *data; void *raw; }} *a = (void*)(intptr_t)v;
  if (a) {{ free(a->raw); free(a); }}
  ```)
;;; Drop [{T}] -- free the array when a bound {T} dies unmoved.

(definstance Drop [{T}] (drop [x] : void ({p}-free x)))
;;; {p}-len -- the element count of a {T}.
;;;
;;; Parameters:
;;;   v -- the array (borrowed)
;;;
;;; Returns:
;;;   The length fixed at construction.
;;;
;;; Example:
;;;   (let [v ({p}-new 8 {exs})]
;;;     ({p}-len v))   ; => 8
;;;
;;; Since: Phase N0

(defn {p}-len [^borrow v : {T}]
  #fx{{}}
  #reads v
  : int
  ```c
  struct {{ int64_t len; {C} *data; void *raw; }} *a = (void*)(intptr_t)v;
  return a->len;
  ```)
;;; {p}-ref -- the element at index i (bounds-checked).
;;;
;;; Parameters:
;;;   v -- the array (borrowed)
;;;   i -- zero-based index; outside [0, len) panics
;;;
;;; Returns:
;;;   The element, typed {E}.
;;;
;;; Example:
;;;   (let [v ({p}-of {e0} {e1})]
;;;     ({p}-ref v 1))   ; => {e1}
;;;
;;; Since: Phase N0

(defn {p}-ref [^borrow v : {T} i : int]
  #fx{{}}
  #reads v
  : {E}
  ```c
  struct {{ int64_t len; {C} *data; void *raw; }} *a = (void*)(intptr_t)v;
  if (i >= 0 && i < a->len) return a->data[i];
  tur_panic("{p}-ref: index out of bounds");
  return 0;
  ```)
;;; {p}-set! -- store x at index i (bounds-checked).
;;;
;;; Parameters:
;;;   v -- the array (borrowed)
;;;   i -- zero-based index; outside [0, len) panics
;;;   x -- the new element
;;;
;;; Example:
;;;   ({p}-set! v 0 {exs})
;;;
;;; Since: Phase N0

(defn {p}-set! [^borrow v : {T} i : int x : {E}]
  #fx{{}}
  #writes v
  : nil
  ```c
  struct {{ int64_t len; {C} *data; void *raw; }} *a = (void*)(intptr_t)v;
  if (i >= 0 && i < a->len) {{ a->data[i] = x; return; }}
  tur_panic("{p}-set!: index out of bounds");
  ```)
;;; {p}-copy -- a fresh {T} with the same elements.
;;;
;;; Parameters:
;;;   v -- the array (borrowed)
;;;
;;; Returns:
;;;   An independent copy, owned by the caller.
;;;
;;; Example:
;;;   (let [c ({p}-copy v)] ({p}-set! c 0 {exs}))   ; v is unchanged
;;;
;;; Since: Phase N0

(defn {p}-copy [^borrow v : {T}]
  #fx{{}}
  : {T}
  ```c
  struct {{ int64_t len; {C} *data; void *raw; }} *a = (void*)(intptr_t)v;
  struct {{ int64_t len; {C} *data; void *raw; }} *c = malloc(sizeof(*c));
  if (!c) {{ fprintf(stderr, "{p}-copy: out of memory\n"); abort(); }}
  c->len = a->len;
  c->raw = malloc((size_t)a->len * sizeof({C}) + 32);
  if (!c->raw) {{ fprintf(stderr, "{p}-copy: out of memory\n"); abort(); }}
  c->data = ({C} *)(((uintptr_t)c->raw + 31) & ~(uintptr_t)31);
  if (a->len > 0) memcpy(c->data, a->data, (size_t)a->len * sizeof({C}));
  return (int64_t)(intptr_t)c;
  ```)
;;; {p}->vec-go__ -- internal: push v[i..n) onto out.

(defn {p}->vec-go__ [^borrow v : {T} out : (Vec {E}) i : int n : int] : (Vec {E})
  (if (>= i n)
    out
    (do
      (vec-push! out ({p}-ref v i))
      ({p}->vec-go__ v out {{i + 1}} n))))
;;; {p}->vec -- copy a {T} into a fresh (Vec {E}).
;;;
;;; Parameters:
;;;   v -- the array (borrowed)
;;;
;;; Returns:
;;;   A growable Vec holding the same elements; the caller frees it.
;;;
;;; Example:
;;;   (let [a ({p}-of {e0} {e1})
;;;         v ({p}->vec a)]
;;;     (vec-len v))   ; => 2
;;;
;;; Since: Phase N0

(defn {p}->vec [^borrow v : {T}] : (Vec {E})
  ({p}->vec-go__ v (:: (vec-new) (Vec {E})) 0 ({p}-len v)))
;;; vec->{p}-go__ -- internal: store src[i..n) into out.

(defn vec->{p}-go__ [^borrow out : {T} ^borrow src : (Vec {E}) i : int n : int] : nil
  (if (>= i n)
    nil
    (do
      ({p}-set! out i (:: (vec-get src i) {E}))
      (vec->{p}-go__ out src {{i + 1}} n))))
;;; vec->{p} -- copy a (Vec {E}) into a fresh {T}.
;;;
;;; Parameters:
;;;   src -- the Vec (borrowed)
;;;
;;; Returns:
;;;   A {T} of the same length and elements, owned by the caller.
;;;
;;; Example:
;;;   (let [v (vec-of {e0} {e1})
;;;         a (vec->{p} v)]
;;;     ({p}-len a))   ; => 2
;;;
;;; Since: Phase N0

(defn vec->{p} [^borrow src : (Vec {E})] : {T}
  (let [out ({p}-new (vec-len src) {zero})]
    (vec->{p}-go__ out src 0 (vec-len src))
    out))
;;; {p}-show-loop__ -- internal: push "e0 e1 ..." onto the builder.

(defn {p}-show-loop__ [^borrow v : {T} i : int n : int b : StringBuilder] : StringBuilder
  (if (= i n)
    b
    (do
      (when (> i 0) (builder/push-cstr! b " "))
      (let [es (show ({p}-ref v i))]
        (do (builder/push-string! b es) (string/release es)))
      ({p}-show-loop__ v {{i + 1}} n b))))
;;; {p}-show -- render a {T} as an owned "#{p}[a b c]" String.
;;;
;;; Parameters:
;;;   v -- the array (borrowed)
;;;
;;; Returns:
;;;   An owned String; release it with string/release.
;;;
;;; Example:
;;;   (let [v ({p}-of {e0} {e1})]
;;;     ({p}-show v))   ; => String "#{p}[{s0} {s1}]"
;;;
;;; Since: Phase N0

(defn {p}-show [^borrow v : {T}] : String
  (let [b (builder/new)]
    (do
      (builder/push-cstr! b "#{p}[")
      ({p}-show-loop__ v 0 ({p}-len v) b)
      (builder/push-cstr! b "]")
      (builder/finish b))))
"""


def render():
    out = [HDR]
    for t in TYPES:
        d = dict(t)
        d["e0"], d["e1"] = t["ex"]
        d["s0"], d["s1"] = {
            "f64vec": ("1.5", "2.5"), "f32vec": ("1.5", "2.5"),
            "i64vec": ("1", "2"), "i32vec": ("1", "2"),
            "u8vec": ("1", "2")}[t["p"]]
        out.append(TEMPLATE.format(**d))
    return "".join(out)


def main():
    text = render()
    if "--check" in sys.argv:
        path = os.path.join(os.path.dirname(os.path.abspath(__file__)),
                            "..", "stdlib", "numvec.tur")
        cur = open(path).read() if os.path.exists(path) else ""
        if cur != text:
            sys.stderr.write("stdlib/numvec.tur is stale: run "
                             "python3 tools/gen-numvec.py > stdlib/numvec.tur\n")
            return 1
        return 0
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
