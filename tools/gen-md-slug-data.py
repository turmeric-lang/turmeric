#!/usr/bin/env python3
"""gen-md-slug-data.py -- markdown-library-plan 6.3: the Unicode data the
heading-id rules (stdlib/markdown/slug.tur) need beyond stdlib/unicode.tur's.

  - What NFKD leaves of a code point in ASCII, for python-markdown's rule.
  - The combining marks (general category Mn, Mc or Me), which GitHub's rule
    keeps along with letters, decimal digits and connector punctuation.

The rest of this docstring is about the first.

python-markdown's toc extension slugs a heading by applying NFKD and then
dropping every character that is not ASCII, so "Resume" with accents becomes
"Resume" and a ligature "fi" becomes "fi".  Per code point that is the ASCII
characters of its full compatibility decomposition, in order: NFKD's
canonical reordering moves only combining marks, which are not ASCII, so it
cannot move one ASCII character past another.  This writes that residue for
every code point past ASCII that has one.

Writes ONE block of C twice, byte for byte, as tools/gen-html-entities.py does:

  stdlib/markdown/slug-data.tur  a file-scope ```c block and two inline-C
                                 wrappers (the compiled back end)
  src/turi/md_slug_data.inc      the same C, #included by
                                 interpreter_natives.c, which registers
                                 natives over the wrappers (the interpreter
                                 cannot run inline C)

tests/check-md-slug-data-sync.sh checks the two copies agree.

The data is UnicodeData.txt's decomposition field, from the Unicode Character
Database tools/fetch-ucd.sh pins, so the table has the Unicode version of
the (scheme char) tables (stdlib/r7rs/unicode.tur):

  bash tools/fetch-ucd.sh
  python3 tools/gen-md-slug-data.py --ucd build/ucd
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def read_ucd(path):
    """({code point: [code points]} with compatibility tags dropped, and the
    sorted code points whose general category is Mn, Mc or Me)."""
    dec, marks = {}, []
    with open(path, encoding="ascii") as f:
        for line in f:
            fields = line.split(";")
            if len(fields) < 6:
                continue
            cp = int(fields[0], 16)
            if fields[2] in ("Mn", "Mc", "Me"):
                marks.append(cp)  # no mark lies in a First/Last range
            if fields[5]:
                parts = fields[5].split()
                if parts[0].startswith("<"):
                    parts = parts[1:]
                dec[cp] = [int(p, 16) for p in parts]
    return dec, sorted(marks)


def runs(cps):
    """[lo, hi] runs of consecutive code points."""
    out = []
    for cp in cps:
        if out and out[-1][1] + 1 == cp:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return out


def full(cp, dec, memo):
    """cp's full compatibility decomposition.  Hangul syllables decompose
    algorithmically into jamo, none of them ASCII, so they need no case."""
    if cp in memo:
        return memo[cp]
    parts = dec.get(cp)
    res = [cp] if parts is None else [x for p in parts for x in full(p, dec, memo)]
    memo[cp] = res
    return res


def residues(dec):
    memo, out = {}, []
    for cp in sorted(dec):
        if cp < 0x80:
            continue
        ascii_part = "".join(chr(x) for x in full(cp, dec, memo) if x < 0x80)
        if ascii_part:
            out.append((cp, ascii_part))
    return out


def c_string(s):
    out = []
    for ch in s:
        o = ord(ch)
        if ch in '"\\?':
            # ? too: a ?? would start a trigraph under -std=c99.
            out.append("\\" + ch)
        elif 0x20 <= o < 0x7F:
            out.append(ch)
        else:
            out.append("\\%03o" % o)
    return "".join(out)


def wrap(items, indent="    ", width=100):
    lines, line = [], indent
    for item in items:
        piece = item + ","
        if len(line) + len(piece) > width:
            lines.append(line.rstrip())
            line = indent
        line += piece
    lines.append(line.rstrip().rstrip(","))
    return "\n".join(lines)


def c_block(table, marks, version):
    blob = "".join(a for _, a in table)
    offsets, at = [], 0
    for _, a in table:
        offsets.append(at)
        at += len(a)
    offsets.append(at)
    chunks, i = [], 0
    while i < len(blob):
        chunks.append('    "%s"' % c_string(blob[i:i + 64]))
        i += 64
    head = """/* markdown-library-plan 6.3 -- GENERATED by tools/gen-md-slug-data.py from
 * UnicodeData.txt (%s).  For each of the %d code points
 * past ASCII whose NFKD holds ASCII, those ASCII bytes, %d in all; then the
 * combining marks (Mn, Mc, Me) as %d runs.  Do not edit: regenerate.  The
 * same text is in stdlib/markdown/slug-data.tur and src/turi/md_slug_data.inc
 * (tests/check-md-slug-data-sync.sh). */
static const uint32_t tur_md_nfkd_cp[%d] = {
""" % (version, len(table), len(blob), len(marks), len(table))
    return (head
            + wrap(["0x%X" % cp for cp, _ in table]) + "\n};\n"
            + "static const uint16_t tur_md_nfkd_at[%d] = {\n" % (len(table) + 1)
            + wrap(["%d" % o for o in offsets]) + "\n};\n"
            + "static const char tur_md_nfkd_ascii[%d] =\n" % (len(blob) + 1)
            + "\n".join(chunks) + ";\n"
            + r"""/* Byte k of the ASCII that NFKD leaves of code point cp, or -1 past its
 * end.  An ASCII cp is its own; one with no entry leaves nothing. */
static int64_t tur_md_nfkd_ascii_byte(int64_t cp, int64_t k) {
    long lo = 0, hi = (long)(sizeof tur_md_nfkd_cp / sizeof *tur_md_nfkd_cp) - 1;
    if (k < 0) return -1;
    if (cp >= 0 && cp < 0x80) return k == 0 ? cp : -1;
    while (lo <= hi) {
        long mid = (lo + hi) / 2;
        if ((int64_t)tur_md_nfkd_cp[mid] == cp) {
            int64_t at = (int64_t)tur_md_nfkd_at[mid] + k;
            return at < (int64_t)tur_md_nfkd_at[mid + 1] ? (int64_t)(unsigned char)tur_md_nfkd_ascii[at] : -1;
        }
        if ((int64_t)tur_md_nfkd_cp[mid] < cp) lo = mid + 1; else hi = mid - 1;
    }
    return -1;
}
"""
            + "static const uint32_t tur_md_mark_runs[%d][2] = {\n" % len(marks)
            + wrap(["{0x%X,0x%X}" % (lo, hi) for lo, hi in marks]) + "\n};\n"
            + r"""/* 1 when code point cp is a combining mark (Mn, Mc or Me), else 0. */
static int64_t tur_md_is_mark(int64_t cp) {
    long lo = 0, hi = (long)(sizeof tur_md_mark_runs / sizeof *tur_md_mark_runs) - 1;
    while (lo <= hi) {
        long mid = (lo + hi) / 2;
        if (cp < (int64_t)tur_md_mark_runs[mid][0]) hi = mid - 1;
        else if (cp > (int64_t)tur_md_mark_runs[mid][1]) lo = mid + 1;
        else return 1;
    }
    return 0;
}
""")


TUR_HEAD = """;;; markdown/slug-data -- the Unicode data the heading-id rules need: NFKD's ASCII, and the combining marks.
;;;
;;; GENERATED by tools/gen-md-slug-data.py -- do not edit; regenerate.  For
;;; each of the %d code points past ASCII whose compatibility decomposition
;;; holds ASCII characters, those characters (python-markdown's rule); and
;;; the combining marks, Mn, Mc and Me (GitHub's).  The source is the Unicode
;;; Character Database that tools/fetch-ucd.sh pins: %s.
;;;
;;; The C below is also src/turi/md_slug_data.inc, which the interpreter
;;; compiles in and registers as natives over the wrappers.
;;;
;;; Since: markdown-library-plan M3
;; The tables are all there is; stdlib/markdown/slug.tur reads them.
"""

TUR_TAIL = """;;; markdown/-nfkd-ascii__ -- internal: byte k of the ASCII that NFKD leaves of code point cp, or -1 past its end.

(defn markdown/-nfkd-ascii__ [cp : int k : int] : int
  ```c
  return tur_md_nfkd_ascii_byte(cp, k);
  ```)
;;; markdown/-mark__ -- internal: 1 when code point cp is a combining mark (Mn, Mc or Me), else 0.

(defn markdown/-mark__ [cp : int] : int
  ```c
  return tur_md_is_mark(cp);
  ```)
"""


def main():
    args = sys.argv[1:]
    if len(args) != 2 or args[0] != "--ucd":
        sys.stderr.write("usage: gen-md-slug-data.py --ucd DIR   (see tools/fetch-ucd.sh)\n")
        return 2
    ucd = args[1]
    try:
        with open(os.path.join(ucd, "ICU_TAG"), encoding="ascii") as f:
            tag = f.read().strip()
        with open(os.path.join(ucd, "DerivedCoreProperties.txt"), encoding="utf-8") as f:
            first = f.readline()  # "# DerivedCoreProperties-16.0.0.txt"
        unicode_version = first.split("-", 1)[1].rsplit(".txt", 1)[0]
    except (OSError, IndexError):
        sys.stderr.write("gen-md-slug-data: %s is not a tools/fetch-ucd.sh directory\n" % ucd)
        return 1
    version = "Unicode %s, ICU %s" % (unicode_version, tag)  # "Unicode 16.0.0, ICU release-76-1"
    dec, marks = read_ucd(os.path.join(ucd, "UnicodeData.txt"))
    table = residues(dec)
    block = c_block(table, runs(marks), version)
    with open(os.path.join(ROOT, "stdlib", "markdown", "slug-data.tur"), "w", encoding="ascii") as f:
        f.write(TUR_HEAD % (len(table), version) + "```c\n" + block + "```\n" + TUR_TAIL)
    with open(os.path.join(ROOT, "src", "turi", "md_slug_data.inc"), "w", encoding="ascii") as f:
        f.write(block)
    print("wrote stdlib/markdown/slug-data.tur and src/turi/md_slug_data.inc "
          "(%d NFKD residues, %d mark runs, from %s)" % (len(table), len(runs(marks)), version))
    return 0


if __name__ == "__main__":
    sys.exit(main())
