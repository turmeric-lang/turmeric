#!/usr/bin/env python3
"""gen-html-entities.py -- markdown-library-plan U2: the HTML named character
references, for CommonMark's entity references (`&copy;`, `&ngE;`).

Writes ONE block of C twice, byte for byte, as tools/gen-r7rs-unicode.py does:

  stdlib/markdown/entities.tur   a file-scope ```c block, two inline-C wrappers
                                 and the public markdown/entity-lookup (the
                                 compiled back end)
  src/turi/html_entities.inc     the same C, #included by interpreter_natives.c,
                                 which registers natives over the two wrappers
                                 (the interpreter cannot run inline C)

tests/check-html-entities-sync.sh checks the two copies agree.

The source is the HTML Standard's list, which WHATWG has frozen ("This list
is static and will not be expanded or changed in the future"):

  python3 tools/gen-html-entities.py                  # CPython's html.entities.html5
  python3 tools/gen-html-entities.py --json FILE      # WHATWG's entities.json

html.spec.whatwg.org is not reachable from every build box (a proxy that
allows GitHub and nothing else), so the default reads CPython's copy, which
CPython generates from the same entities.json.  Either way only the names
that end in ';' are kept -- CommonMark reads no entity without its semicolon
-- and the table is checked against a pinned SHA-256 digest of its canonical
text (one "name<TAB>codepoints" line per entry, the name without its ';').
A source that differs fails here rather than shipping a different table.
"""
import hashlib
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EXPECTED_COUNT = 2125
EXPECTED_SHA256 = "71a635465d283bf575ff291be712031532bd7aa34723faa01cb20ae82b8be097"


def from_python():
    import html.entities
    out = {}
    for key, chars in html.entities.html5.items():
        if key.endswith(";"):
            out[key[:-1]] = [ord(ch) for ch in chars]
    return out


def from_json(path):
    with open(path, encoding="utf-8") as f:
        data = json.load(f)
    out = {}
    for key, entry in data.items():
        if key.startswith("&") and key.endswith(";"):
            out[key[1:-1]] = list(entry["codepoints"])
    return out


def canonical(table):
    return "".join("%s\t%s\n" % (name, " ".join("%X" % cp for cp in table[name]))
                   for name in sorted(table))


def c_block(table, digest):
    names = sorted(table)
    rows = []
    for name in names:
        cps = table[name] + [0]
        rows.append('{"%s",{0x%X,0x%X}}' % (name, cps[0], cps[1]))
    lines, line = [], "    "
    for row in rows:
        piece = row + ","
        if len(line) + len(piece) > 100:
            lines.append(line.rstrip())
            line = "    "
        line += piece
    lines.append(line.rstrip().rstrip(","))
    head = """/* markdown-library-plan U2 -- GENERATED by tools/gen-html-entities.py from
 * the HTML Standard's named character references: the %d that end in ';',
 * stored without it.  Table digest:
 * sha256:%s
 * Do not edit: regenerate.  The same text is in stdlib/markdown/entities.tur
 * and src/turi/html_entities.inc (tests/check-html-entities-sync.sh). */
typedef struct { const char *name; uint32_t cp[2]; } tur_html_entity;
static const tur_html_entity tur_html_entities[%d] = {
""" % (len(names), digest, len(names))
    code = r"""};
/* The index of the entity named name (without '&' and ';'), or -1.  The
 * table is sorted by strcmp, so this is a binary search. */
static int64_t tur_html_entity_find(const char *name) {
    long lo = 0, hi = (long)(sizeof tur_html_entities / sizeof *tur_html_entities) - 1;
    if (!name) return -1;
    while (lo <= hi) {
        long mid = (lo + hi) / 2;
        int c = strcmp(tur_html_entities[mid].name, name);
        if (c == 0) return mid;
        if (c < 0) lo = mid + 1; else hi = mid - 1;
    }
    return -1;
}
/* Code point k (0 or 1) of entity i, or 0 when there is none: most
 * entities are one code point, a few are two. */
static int64_t tur_html_entity_cp(int64_t i, int64_t k) {
    if (i < 0 || (size_t)i >= sizeof tur_html_entities / sizeof *tur_html_entities) return 0;
    if (k < 0 || k > 1) return 0;
    return (int64_t)tur_html_entities[i].cp[k];
}
"""
    return head + "\n".join(lines) + "\n" + code


TUR_HEAD = """;;; markdown/entities -- the HTML named character references, for &name; in Markdown.
;;;
;;; GENERATED by tools/gen-html-entities.py -- do not edit; regenerate.  The
;;; table is the HTML Standard's: the %d names that end in ';' (CommonMark
;;; reads no entity without one), from a source pinned by a digest of the
;;; table.  The C below is also src/turi/html_entities.inc, which the
;;; interpreter compiles in and registers as natives over the two wrappers.
;;;
;;; Since: markdown-library-plan U2
;; UTF-8 encoding comes from stdlib/unicode.tur.
(load "stdlib/unicode.tur")

"""

TUR_TAIL = """;;; markdown/-entity-find__ -- internal: the index of the entity named name, or -1.

(defn markdown/-entity-find__ [name : cstr] : int
  ```c
  return tur_html_entity_find(name);
  ```)
;;; markdown/-entity-cp__ -- internal: code point k (0 or 1) of entity i, or 0.

(defn markdown/-entity-cp__ [i : int k : int] : int
  ```c
  return tur_html_entity_cp(i, k);
  ```)
;;; markdown/entity-lookup -- the text an HTML named character reference stands for.
;;;
;;; name is the reference without its & and ;: "copy" for &copy;.  Names are
;;; case-sensitive, as in HTML ("AMP" and "amp" are both entities, "Amp" is
;;; not), and a name the HTML Standard lists only without a semicolon is not
;;; found, as CommonMark requires.  Most entities are one code point; a few,
;;; such as "ngE", are two.
;;;
;;; Parameters:
;;;   name -- the entity name, without & and ; (borrowed)
;;;
;;; Returns:
;;;   (some s) with a fresh owned String of the character(s) in UTF-8, or
;;;   (none) when name is not an entity.
;;;
;;; Example:
;;;   (markdown/entity-lookup (string/from-cstr "amp"))  ; => (some "&")
;;;
;;; Since: markdown-library-plan U2
(defn markdown/entity-lookup [name : String] : (Option String)
  (let [i (markdown/-entity-find__ (string/to-cstr name))]
    (if (< i 0)
      (none)
      (let [b  (builder/new)
            c2 (markdown/-entity-cp__ i 1)]
        (do
          (utf8/push-char! b (int->char (markdown/-entity-cp__ i 0)))
          (when (> c2 0) (utf8/push-char! b (int->char c2)))
          (some (builder/finish b)))))))
"""


def main():
    args = sys.argv[1:]
    if args == []:
        table, source = from_python(), "CPython %s html.entities.html5" % sys.version.split()[0]
    elif len(args) == 2 and args[0] == "--json":
        table, source = from_json(args[1]), args[1]
    else:
        sys.stderr.write("usage: gen-html-entities.py [--json entities.json]\n")
        return 2
    text = canonical(table)
    digest = hashlib.sha256(text.encode("utf-8")).hexdigest()
    if len(table) != EXPECTED_COUNT or digest != EXPECTED_SHA256:
        sys.stderr.write(
            "gen-html-entities: %s gives %d entities, digest %s;\n"
            "expected %d, digest %s.  The HTML entity list is frozen, so a\n"
            "difference means the source is not the HTML Standard's list.\n"
            % (source, len(table), digest, EXPECTED_COUNT, EXPECTED_SHA256))
        return 1
    block = c_block(table, digest)
    tur_dir = os.path.join(ROOT, "stdlib", "markdown")
    os.makedirs(tur_dir, exist_ok=True)
    with open(os.path.join(tur_dir, "entities.tur"), "w", encoding="ascii") as f:
        f.write(TUR_HEAD % len(table) + "```c\n" + block + "```\n" + TUR_TAIL)
    with open(os.path.join(ROOT, "src", "turi", "html_entities.inc"), "w", encoding="ascii") as f:
        f.write(block)
    print("wrote stdlib/markdown/entities.tur and src/turi/html_entities.inc "
          "(%d entities from %s)" % (len(table), source))
    return 0


if __name__ == "__main__":
    sys.exit(main())
